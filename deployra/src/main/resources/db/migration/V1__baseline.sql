CREATE TABLE entitlement_keys (
    code          varchar(64)  NOT NULL,
    description   varchar(255),
    unit          varchar(20),
    default_limit bigint       NOT NULL,
    is_additive   boolean      NOT NULL,
    CONSTRAINT pk_entitlement_keys PRIMARY KEY (code)
);

CREATE TABLE subscription_plans (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY,
    code                varchar(50)    NOT NULL,
    name                varchar(255)   NOT NULL,
    price               numeric(12, 2) NOT NULL,
    currency            varchar(3)     NOT NULL,
    billing_period_days integer        NOT NULL,
    is_active           boolean        NOT NULL,
    sort_order          integer        NOT NULL,
    CONSTRAINT pk_subscription_plans PRIMARY KEY (id),
    CONSTRAINT uk_subscription_plans_code UNIQUE (code)
);

CREATE TABLE plan_entitlements (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    plan_id         bigint      NOT NULL,
    entitlement_key varchar(64) NOT NULL,
    limit_value     bigint,
    CONSTRAINT pk_plan_entitlements PRIMARY KEY (id),
    CONSTRAINT uk_plan_entitlements_plan_key UNIQUE (plan_id, entitlement_key),
    CONSTRAINT fk_plan_entitlements_plan FOREIGN KEY (plan_id) REFERENCES subscription_plans (id),
    CONSTRAINT fk_plan_entitlements_key FOREIGN KEY (entitlement_key) REFERENCES entitlement_keys (code)
);

CREATE TABLE addon_packages (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    name            varchar(255)   NOT NULL,
    entitlement_key varchar(64)    NOT NULL,
    delta           bigint         NOT NULL,
    validity_type   varchar(20)    NOT NULL,
    validity_days   integer,
    price           numeric(12, 2) NOT NULL,
    is_active       boolean        NOT NULL,
    CONSTRAINT pk_addon_packages PRIMARY KEY (id),
    CONSTRAINT fk_addon_packages_key FOREIGN KEY (entitlement_key) REFERENCES entitlement_keys (code),
    CONSTRAINT ck_addon_packages_validity_type CHECK (validity_type IN ('DAYS', 'CALENDAR_MONTH'))
);

-- 2. Tài khoản, thanh toán -------------------------------------------

CREATE TABLE users (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY,
    email                varchar(255) NOT NULL,
    password             varchar(255) NOT NULL,
    first_name           varchar(255),
    last_name            varchar(255),
    is_active            boolean      NOT NULL,
    google_id            varchar(255),
    subscription_plan_id bigint,
    created_at           timestamp(6) with time zone NOT NULL,
    last_login           timestamp(6) with time zone,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT fk_users_subscription_plan FOREIGN KEY (subscription_plan_id) REFERENCES subscription_plans (id)
);

CREATE TABLE payments (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id         bigint         NOT NULL,
    plan_id         bigint,
    purpose         varchar(10)    NOT NULL,
    amount          numeric(12, 2) NOT NULL,
    currency        varchar(3)     NOT NULL,
    status          varchar(20)    NOT NULL,
    provider        varchar(30),
    provider_txn_id varchar(255),
    created_at      timestamp(6) with time zone NOT NULL,
    CONSTRAINT pk_payments PRIMARY KEY (id),
    CONSTRAINT uk_payments_provider_txn_id UNIQUE (provider_txn_id),
    CONSTRAINT fk_payments_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_payments_plan FOREIGN KEY (plan_id) REFERENCES subscription_plans (id),
    CONSTRAINT ck_payments_purpose CHECK (purpose IN ('PLAN', 'ADDON')),
    CONSTRAINT ck_payments_status CHECK (status IN ('PENDING', 'SUCCEEDED', 'FAILED', 'REFUNDED'))
);

CREATE TABLE user_subscriptions (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id              bigint      NOT NULL,
    plan_id              bigint      NOT NULL,
    status               varchar(20) NOT NULL,
    current_period_start timestamp(6) with time zone NOT NULL,
    current_period_end   timestamp(6) with time zone NOT NULL,
    payment_id           bigint,
    created_at           timestamp(6) with time zone NOT NULL,
    CONSTRAINT pk_user_subscriptions PRIMARY KEY (id),
    CONSTRAINT fk_user_subscriptions_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_user_subscriptions_plan FOREIGN KEY (plan_id) REFERENCES subscription_plans (id),
    CONSTRAINT fk_user_subscriptions_payment FOREIGN KEY (payment_id) REFERENCES payments (id),
    CONSTRAINT ck_user_subscriptions_status CHECK (status IN ('ACTIVE', 'EXPIRED', 'CANCELLED'))
);
CREATE INDEX idx_user_subscriptions_user_status ON user_subscriptions (user_id, status);

CREATE TABLE user_addons (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id         bigint      NOT NULL,
    package_id      bigint      NOT NULL,
    entitlement_key varchar(64) NOT NULL,
    delta           bigint      NOT NULL,
    payment_id      bigint,
    starts_at       timestamp(6) with time zone NOT NULL,
    expires_at      timestamp(6) with time zone NOT NULL,
    created_at      timestamp(6) with time zone NOT NULL,
    CONSTRAINT pk_user_addons PRIMARY KEY (id),
    CONSTRAINT uk_user_addons_payment UNIQUE (payment_id),
    CONSTRAINT fk_user_addons_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_user_addons_package FOREIGN KEY (package_id) REFERENCES addon_packages (id),
    CONSTRAINT fk_user_addons_key FOREIGN KEY (entitlement_key) REFERENCES entitlement_keys (code),
    CONSTRAINT fk_user_addons_payment FOREIGN KEY (payment_id) REFERENCES payments (id)
);
CREATE INDEX idx_user_addons_user_key ON user_addons (user_id, entitlement_key);

CREATE TABLE user_entitlement_overrides (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id         bigint      NOT NULL,
    entitlement_key varchar(64) NOT NULL,
    limit_value     bigint,
    reason          varchar(255),
    expires_at      timestamp(6) with time zone,
    created_at      timestamp(6) with time zone NOT NULL,
    CONSTRAINT pk_user_entitlement_overrides PRIMARY KEY (id),
    CONSTRAINT uk_user_entitlement_overrides_user_key UNIQUE (user_id, entitlement_key),
    CONSTRAINT fk_user_entitlement_overrides_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_user_entitlement_overrides_key FOREIGN KEY (entitlement_key) REFERENCES entitlement_keys (code)
);

-- 3. PaaS: project, service, deploy -----------------------------------

CREATE TABLE projects (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    owner_id   bigint       NOT NULL,
    name       varchar(255) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    deleted_at timestamp(6) with time zone,
    CONSTRAINT pk_projects PRIMARY KEY (id),
    CONSTRAINT fk_projects_owner FOREIGN KEY (owner_id) REFERENCES users (id)
);

CREATE TABLE services (
    id               bigint GENERATED BY DEFAULT AS IDENTITY,
    project_id       bigint       NOT NULL,
    name             varchar(255) NOT NULL,
    slug             varchar(64)  NOT NULL,
    service_type     varchar(20)  NOT NULL,
    status           varchar(20)  NOT NULL,
    repo_url         varchar(500),
    branch           varchar(255),
    root_dir         varchar(255),
    dockerfile_path  varchar(255),
    port             integer,
    healthcheck_path varchar(255),
    memory_mb        integer      NOT NULL,
    cpu_millicores   integer      NOT NULL,
    volume_bytes     bigint       NOT NULL,
    node_id          bigint,
    last_active_at   timestamp(6) with time zone,
    suspended_at     timestamp(6) with time zone,
    suspended_reason varchar(30),
    created_at       timestamp(6) with time zone NOT NULL,
    deleted_at       timestamp(6) with time zone,
    CONSTRAINT pk_services PRIMARY KEY (id),
    CONSTRAINT uk_services_slug UNIQUE (slug),
    CONSTRAINT fk_services_project FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT ck_services_type CHECK (service_type IN ('APP', 'DATABASE')),
    CONSTRAINT ck_services_status CHECK (status IN ('IDLE', 'RUNNING', 'SLEEPING', 'STOPPED', 'FAILED', 'SUSPENDED')),
    CONSTRAINT ck_services_suspended_reason CHECK (suspended_reason IN ('BANDWIDTH_EXCEEDED', 'MEMORY_OVER_QUOTA', 'PLAN_EXPIRED', 'ABUSE'))
);

CREATE TABLE source_uploads (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id         bigint       NOT NULL,
    storage_backend varchar(10)  NOT NULL,
    object_key      varchar(500) NOT NULL,
    size_bytes      bigint       NOT NULL,
    sha256          varchar(64),
    created_at      timestamp(6) with time zone NOT NULL,
    expires_at      timestamp(6) with time zone,
    deleted_at      timestamp(6) with time zone,
    CONSTRAINT pk_source_uploads PRIMARY KEY (id),
    CONSTRAINT fk_source_uploads_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_source_uploads_backend CHECK (storage_backend IN ('S3', 'R2', 'LOCAL'))
);

CREATE TABLE deployments (
    id            bigint GENERATED BY DEFAULT AS IDENTITY,
    service_id    bigint      NOT NULL,
    status        varchar(20) NOT NULL,
    trigger_type  varchar(20) NOT NULL,
    source_type   varchar(10) NOT NULL,
    commit_sha    varchar(64),
    upload_id     bigint,
    image         varchar(500),
    image_bytes   bigint,
    image_pruned  boolean     NOT NULL,
    build_seconds integer,
    build_log     text,
    created_at    timestamp(6) with time zone NOT NULL,
    finished_at   timestamp(6) with time zone,
    CONSTRAINT pk_deployments PRIMARY KEY (id),
    CONSTRAINT fk_deployments_service FOREIGN KEY (service_id) REFERENCES services (id),
    CONSTRAINT fk_deployments_upload FOREIGN KEY (upload_id) REFERENCES source_uploads (id),
    CONSTRAINT ck_deployments_status CHECK (status IN ('QUEUED', 'BUILDING', 'DEPLOYING', 'LIVE', 'INACTIVE', 'FAILED', 'CANCELLED')),
    CONSTRAINT ck_deployments_trigger CHECK (trigger_type IN ('MANUAL', 'WEBHOOK', 'REDEPLOY', 'ROLLBACK')),
    CONSTRAINT ck_deployments_source CHECK (source_type IN ('GIT', 'ZIP'))
);
CREATE INDEX idx_deployments_service_created ON deployments (service_id, created_at);

CREATE TABLE variables (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    service_id      bigint       NOT NULL,
    var_key         varchar(255) NOT NULL,
    value_encrypted text         NOT NULL,
    CONSTRAINT pk_variables PRIMARY KEY (id),
    CONSTRAINT uk_variables_service_key UNIQUE (service_id, var_key),
    CONSTRAINT fk_variables_service FOREIGN KEY (service_id) REFERENCES services (id)
);

CREATE TABLE bandwidth_usage_daily (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    service_id bigint NOT NULL,
    usage_date date   NOT NULL,
    bytes_out  bigint NOT NULL,
    CONSTRAINT pk_bandwidth_usage_daily PRIMARY KEY (id),
    CONSTRAINT uk_bandwidth_usage_daily_service_date UNIQUE (service_id, usage_date),
    CONSTRAINT fk_bandwidth_usage_daily_service FOREIGN KEY (service_id) REFERENCES services (id)
);
